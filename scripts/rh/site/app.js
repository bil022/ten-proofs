const DECL = /^(?:@\[|\/--|\/-!|theorem\b|lemma\b|def\b|abbrev\b|instance\b|structure\b|inductive\b|class\b|opaque\b|axiom\b|private\b|protected\b|noncomputable\b|public\b|nonrec\b|partial\b|unsafe\b|meta\b|namespace\b|end\b|section\b|open\b|variable\b|set_option\b|attribute\b|universe\b|example\b|macro\b|syntax\b|elab\b|scoped\b|local\b|omit\b|include\b|#)/;

// Without recorded lines: find "theorem <name>" (or def, …) by the end of the name.
function findDecl(lines, name) {
  const parts = name.split(".");
  for (let k = parts.length; k >= 1; k--) {
    const suffix = parts.slice(-k).join(".").replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const re = new RegExp(String.raw`^\s*(?:@\[[^\]]*\]\s*)*(?:(?:private|protected|noncomputable|public|nonrec|partial|unsafe|meta)\s+)*(?:theorem|lemma|def|abbrev|instance|structure|inductive|class|opaque|axiom)\s+(?:\{[^}]*\}\s*)?«?${suffix}»?(?=[\s:({\[]|$)`);
    const i = lines.findIndex((l) => re.test(l));
    if (i >= 0) {
      let j = i + 1;
      while (j < lines.length && !DECL.test(lines[j])) j++;
      while (j > i + 1 && !lines[j - 1].trim()) j--;
      return [i + 1, j];
    }
  }
  return null;
}

function nodeById(id) {
  const p = current.page;
  if (id === current.id) return { id, name: p.name, kind: p.kind, module: p.module, first: p.lines[0], last: p.lines[1] };
  const k = p.kids.find((x) => x[0] === id);
  return k && kidNode(k);
}

function hideCode() {
  $("code").hidden = true;
  const wasOpen = !$("graphpane").classList.contains("withcode") ? false : true;
  $("graphpane").classList.remove("withcode");
  if (cy) { cy.resize(); if (wasOpen && current) { cy.fit(undefined, 30); if (cy.zoom() > 1.3) { cy.zoom(1.3); cy.center(); } } placeUp(); }
}

async function showCode(id) {
  const node = nodeById(id);
  if (!node || node.module === "Main" || node.module === "?") return;
  const box = $("code"), src = $("codeSrc"), gut = $("codeGutter");
  const opening = box.hidden;
  box.hidden = false;
  $("graphpane").classList.add("withcode");
  cy.resize();
  if (opening) { cy.fit(undefined, 30); if (cy.zoom() > 1.3) { cy.zoom(1.3); cy.center(); } }
  placeUp();
  $("codeName").textContent = node.name;
  $("codeNote").textContent = "";
  $("codeLink").textContent = node.module;
  $("codeLink").href = sourceUrl(node.module);
  gut.textContent = "";
  src.innerHTML = `<span class="msg">${t().codeLoading}</span>`;
  box.dataset.id = id;
  const url = rawUrl(node.module);
  let text;
  try {
    if (!fileCache.has(url)) fileCache.set(url, fetch(url).then((r) => { if (!r.ok) throw new Error(r.status); return r.text(); }));
    text = await fileCache.get(url);
  } catch (e) {
    fileCache.delete(url);
    src.innerHTML = `<span class="msg">${t().codeFail}${esc(e.message)}</span>`;
    return;
  }
  if (box.dataset.id !== String(id)) return;  // another node was chosen meanwhile
  const lines = text.split("\n");
  let a = node.first, b = node.last, guessed = false;
  if (!a) {
    const f = findDecl(lines, node.name);
    if (!f) {
      src.innerHTML = `<span class="msg">${node.kind === "?" ? t().codeAux : t().codeMissing}</span>`;
      return;
    }
    [a, b] = f;
    guessed = true;
  }
  const end = Math.min(b, a + MAXLINES - 1);
  const notes = [];
  if (guessed) notes.push(t().codeGuess);
  if (end < b) notes.push(t().codeCut(MAXLINES));
  $("codeNote").textContent = notes.join(" · ");
  $("codeLink").textContent = `${node.module}:${a}–${b}`;
  $("codeLink").href = `${sourceUrl(node.module)}#L${a}-L${b}`;
  const body = lines.slice(a - 1, end);
  gut.textContent = body.map((_, i) => a + i).join("\n");
  src.innerHTML = highlightLean(body.join("\n"));
  box.querySelector(".codeBody").scrollTop = 0;
}

// ---------------------------------------------------------------- search
async function loadNames() {
  if (names) return names;
  const text = await gunzipText("data/names.tsv.gz");
  const list = [], parent = new Map();
  for (const line of text.split("\n")) {
    if (!line) continue;
    const [n, id, par, size, nk] = line.split("\t");
    const rec = { n, l: n.toLowerCase(), id: +id, par: +par, size: +size, nk: +nk };
    list.push(rec);
    parent.set(rec.id, rec.par);
  }
  names = { list, parent };
  return names;
}

let searchTimer = null, hits = [], hitIdx = -1;
async function search() {
  const q = $("q").value.trim().toLowerCase();
  const box = $("hits");
  if (q.length < 3) { box.hidden = true; return; }
  box.hidden = false;
  if (!names) box.innerHTML = `<li class="msg">${t().loadingNames}</li>`;
  await loadNames();
  if ($("q").value.trim().toLowerCase() !== q) return;
  hits = [];
  for (const r of names.list) if (r.l.includes(q)) hits.push(r);
  hits.sort((a, b) => (b.l === q) - (a.l === q) || b.size - a.size);
  hits = hits.slice(0, 40);
  hitIdx = -1;
  box.innerHTML = hits.length
    ? hits.map((r, i) => `<li data-i="${i}"><span class="n" title="${esc(r.n)}">${esc(r.n)}</span><span class="s">${fmt(r.size)}</span></li>`).join("")
    : `<li class="msg">${t().noHits}</li>`;
}

function openHit(r) {
  $("hits").hidden = true;
  location.hash = r.nk ? String(r.id) : `${r.par}:${r.id}`;
}

